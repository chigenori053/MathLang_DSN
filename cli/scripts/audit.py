#!/usr/bin/env python3
"""Independent raw-artifact recount; does not trust summary PASS labels."""
import argparse, collections, hashlib, json, subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];E=ROOT/'cli/evidence'
p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);a=p.parse_args()
load=lambda p:json.loads(p.read_text())
digest=lambda b:hashlib.sha256(b).hexdigest()
compact=lambda v:json.dumps(v,ensure_ascii=False,separators=(',',':')).encode()
def manifest(root):
 for name,sha in load(root/'artifact_manifest.json').items():
  path=root/name;assert not path.is_symlink() and path.resolve().is_relative_to(root.resolve());assert digest(path.read_bytes())==sha,(root,name)
def audit_run(root):
 manifest(root)
 for name,sha in load(root/'source_manifest.json').items():
  base=ROOT/'verification' if not name.startswith(('cli/','mirp/','verification/')) else ROOT
  assert digest((base/name).read_bytes())==sha,('source changed',name)
 obligations=load(root/'proof_obligations.json');by_id={o['id']:o for o in obligations};assert len(by_id)==9
 results=load(root/'proof_results.json');assert len(results)==27
 expected={'MV-01':'PROVED','MV-02':'REFUTED','MV-03':'PROVED','MV-04':'PROVED','MV-05':'PROVED','MV-06':'PROVED','CV-UPDATE':'PROVED','CV-PHASE':'PROVED','CV-PHASE-COLLISION':'REFUTED'}
 counts=collections.Counter();semantic=[]
 for e in results:
  o=by_id[e['obligation_id']];k=e['toolchain'];copy=dict(e);copy['evidence_id']=''
  assert digest(compact(copy))==e['evidence_id']
  path=root/'registry'/e['evidence_id'];assert load(path/'evidence.json')==e
  for name,sha in e['artifact_hashes'].items():
   assert Path(name).name==name and digest((path/name).read_bytes())==sha
  assert e['model_id']==o['model_id'] and e['model_revision']==o['model_revision']
  assert e['proof_result']==k['status']==expected[o['id']]
  assert k['sandboxed'] and k['toolchain_verified'] and k['exit_code']==0 and not k['timed_out']
  assert k['peak_rss_bytes']<=2147483648 and k['elapsed_ms']<=300000
  assert k['checked_modules']==['Foundation','Independent','Generated']
  assert set(k['axioms'])<= {'propext','Classical.choice','Quot.sound'}
  assert e['lean_source_hash']==k['source_hash']==e['translation']['lean_module_hash']
  assert e['dependencies']==o['dependencies'] and e['assumptions']==o['assumptions']
  counts[o['id']]+=1
  semantic.append({key:e[key] for key in ['model_id','model_revision','obligation_id','source_ir_hash','lean_source_hash','proof_result','assumptions','dependencies','translation','recipe']})
 assert dict(counts)=={k:3 for k in expected}
 assert semantic[:9]==semantic[9:18]==semantic[18:]
 return obligations,semantic,dict(collections.Counter(e['proof_result'] for e in results))
old_o,old,counts=audit_run(E/'formal-legacy');new_o,new,new_counts=audit_run(E/'formal-final');assert old_o==new_o and old==new
assert load(E/'formal-legacy/repeatability.json')['identical']
for name,sha in load(E/'baseline/legacy/source_manifest.json').items():assert digest((ROOT/name).read_bytes())==sha
baseline=load(E/'baseline/legacy/commands.json');assert all(r['passed'] for r in baseline[:3])
assert load(E/'baseline/legacy/summary.json')['rust_tests_passed']==77
assert all(r['passed'] for r in load(E/'baseline/reason-clean.json'))
# Compare the new unannotated plan to hashes freshly generated by the old CLI.
plan_dir=E/'plan-regression';plan_dir.mkdir(exist_ok=True)
old_plans=load(E/'formal-legacy/dependency_graph.json');hashes=load(E/'formal-legacy/repeatability.json')['runs'][0]
def order_like(template,v):
 if isinstance(v,dict):
  assert set(template)==set(v);return {k:(v[k] if k=="evidence_refs" else order_like(template[k],v[k])) for k in template}
 if isinstance(v,list):
  assert len(template)==len(v);return [order_like(x,y) for x,y in zip(template,v)]
 return v
plans=[]
for i,o in enumerate(new_o):
 input=plan_dir/(o['id']+'.json');input.write_text(json.dumps(o))
 cmd=[str(ROOT/'cli/target/local-install/bin/mathlang'),'proof','plan',str(input),'--format','json']
 r=subprocess.run(cmd,capture_output=True,text=True,timeout=30);assert r.returncode==0
 (plan_dir/(o['id']+'.stdout.json')).write_text(r.stdout);(plan_dir/(o['id']+'.stderr.log')).write_text(r.stderr)
 plan=order_like(old_plans[i],json.loads(r.stdout)['result']);sha=digest(compact(plan));assert sha==hashes[o['id']]['plan_hash']
 plans.append(dict(obligation_id=o['id'],plan_hash=sha,command=cmd,passed=True))
(plan_dir/'commands.json').write_text(json.dumps(plans,indent=2))
for folder in ['acceptance-final','acceptance-installed']:
 manifest(E/folder);records=load(E/folder/'commands.json');assert len(records)==40
 for r in records:
  assert r['exit_code']==r['expected_exit_code'];assert (E/folder/r['stdout']).exists() and (E/folder/r['stderr']).exists()
 assert load(E/folder/'regression_results.json')['semantic_state']
 for label,status in [('false','UNKNOWN'),('incomplete','UNKNOWN'),('refuted','REFUTED'),('missing-runner','ERROR')]:
  assert load(E/folder/(label+'.stdout.log'))['formal_status']==status
 assert load(E/folder/'tampered.stdout.log')['error']['category']=='EVIDENCE'
negative=load(E/'negative-lean/commands.json');assert len(negative)==6 and all(r['status']=='PASS' for r in negative)
for label in ['LV-05-false','LV-06-incomplete']:
 raw=load(E/'negative-lean'/label/'proof_results.json');assert raw['proof_result']=='UNKNOWN' and raw['toolchain']['exit_code']!=0
for label in ['LV-07-axiom','LV-06-sorry','LV-09-weakened','LV-SAFE-fork']:
 raw=load(E/'negative-lean'/(label+'.result.json'));assert raw['sandboxed'] and raw['toolchain_verified'] and raw['status'] in ['UNKNOWN','ERROR']
assert len(load(E/'translations/cases.json'))==11
assert load(E/'translations/kernel.json')['status']=='PROVED'
rust_log=(E/'tests.stdout.log').read_text();assert 'test result: ok. 5 passed' in rust_log and 'test result: ok. 1 passed' in rust_log
assert '33 passed' in (E/'baseline/verification.stdout.log').read_text()
installed=E/'acceptance-installed';doctor=load(installed/'doctor.stdout.log')['result']
assert doctor['readiness']=='PARTIAL' and '0.5.6.10' in doctor['checks']['reason']['stdout']
report=dict(schema_version='mathlang.cli.audit/0.1',raw_audit='PASS',final_acceptance='PARTIAL',phase_gates={'P0':'PASS','P1':'PASS','P2':'PASS','P3':'PASS','P4':'PASS','P5':'PARTIAL'},formal_legacy=counts,formal_new=new_counts,obligations=9,repetitions=3,plan_hashes_matched=len(plans),cli_commands_debug=40,cli_commands_installed=40,baseline_rust_tests=77,verification_rust_tests=33,cli_rust_tests=6,independent_translation_checks=11,lean_negative_cases=6,unchanged_core_sources=True,remaining=['ReasonScript required 0.5.6.5; tested installed 0.5.6.10','Actual Lean 300-second or 2-GiB exhaustion not induced; fixed runner limits, finite-search exhaustion and child-process deadline tested'])
assert not a.output.exists();a.output.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))
